import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repository = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const writerCommit = "05319ea";
const output = path.join(repository, "tests/fixtures/p2-prior-writer-v1.json");
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "p2-prior-writer-"));
const boundedExec = (
  command: string,
  args: string[],
  options: Parameters<typeof execFileSync>[2] = {},
) =>
  execFileSync(command, args, {
    ...options,
    timeout: 30_000,
    killSignal: "SIGKILL",
  });
try {
  boundedExec("git", ["archive", writerCommit], {
    cwd: repository,
    stdio: [
      "ignore",
      fs.openSync(path.join(temp, "archive.tar"), "w"),
      "inherit",
    ],
  });
  boundedExec("tar", ["-xf", path.join(temp, "archive.tar"), "-C", temp]);
  fs.symlinkSync(
    path.join(repository, "node_modules"),
    path.join(temp, "node_modules"),
    "dir",
  );
  const recordPath = path.join(temp, "task-execution-record.mts");
  fs.writeFileSync(
    recordPath,
    `
    import { TaskExecutionStore } from "./src/task-session/task-execution-store.ts";
    const root = process.env.P2_WRITER_ROOT!;
    const project = { id: "p2-upgrade-fixture", repository: { path: root + "/repo", worktreeRoot: root + "/worktrees", defaultBranch: "main" } };
    const store = new TaskExecutionStore(root + "/runtime", project);
    const base = {
      version: 1, projectId: project.id, cardId: "card-prior-writer", phase: "human-feedback",
      primarySessionId: "session-prior-writer", expectedBranch: "agent/card-prior-writer",
      pullRequest: { number: 73, url: "https://github.com/example/project/pull/73", headSha: "${"a".repeat(40)}" },
      operationKey: "feedback-73-2", revision: 1,
      retryCounters: { validation: 1, review: 0, ci: 1, humanFeedback: 2 },
      createdAt: "2026-10-01T10:00:00.000Z", updatedAt: "2026-10-01T10:02:00.000Z",
    };
    store.create(base);
    for (let revision = 1; revision < 4; revision++) {
      const current = store.read(base.cardId)!;
      store.compareAndSwap(base.cardId, revision, { ...current, revision: revision + 1, updatedAt: "2026-10-01T10:02:00.000Z" });
    }
    process.stdout.write(JSON.stringify(store.read(base.cardId)) + "\\n");
  `,
  );
  const runner = path.join(temp, "run-writer.mts");
  fs.writeFileSync(
    runner,
    `import { pathToFileURL } from "node:url"; await import(pathToFileURL(${JSON.stringify(recordPath)}).href);`,
  );
  const root = path.join(temp, "writer-state");
  fs.mkdirSync(path.join(root, "repo"), { recursive: true });
  fs.mkdirSync(path.join(root, "worktrees"), { recursive: true });
  const bytes = boundedExec(
    path.join(repository, "node_modules/.bin/tsx"),
    [runner],
    {
      cwd: temp,
      env: { ...process.env, P2_WRITER_ROOT: root },
    },
  );
  const task = JSON.parse(bytes.toString("utf8")) as Record<string, unknown>;
  const sourcePaths = [
    "src/task-session/task-execution-record.ts",
    "src/task-session/task-execution-store.ts",
  ];
  const sourceHashes = Object.fromEntries(
    sourcePaths.map((relative) => [
      relative,
      createHash("sha256")
        .update(
          boundedExec("git", ["show", `${writerCommit}:${relative}`], {
            cwd: repository,
          }),
        )
        .digest("hex"),
    ]),
  );
  const artifact = {
    provenance: {
      writerCommit: boundedExec(
        "git",
        ["rev-parse", `${writerCommit}^{commit}`],
        { cwd: repository, encoding: "utf8" },
      ).trim(),
      sourceHashes,
      artifactVersion: 1,
      schema: "TaskExecutionRecord v1",
      direction:
        "writer 05319ea TaskExecutionStore -> current RunStore legacy importer",
      note: "Generated by the real prior committed writer code, not by a current-version serializer.",
    },
    record: task,
  };
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, `${JSON.stringify(artifact, null, 2)}\n`);
  process.stdout.write(
    `${JSON.stringify({ output, artifactSha256: createHash("sha256").update(fs.readFileSync(output)).digest("hex"), sourceHashes }, null, 2)}\n`,
  );
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
